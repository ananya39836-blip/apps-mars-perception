        return {
            'total_events_processed': len(events),
            'spikes_fired': self.spike_count,
            'spike_rate_hz': float(spike_rate_hz),
            'is_dynamic_hazard_detected': is_hazard,
            'estimated_power_watts': round(power_watts, 3),
            'single_event_upset': self.radiation_bitflip_detected
        }

