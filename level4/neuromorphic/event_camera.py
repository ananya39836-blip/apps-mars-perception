class NeuromorphicEventStream:
    """Simulates asynchronous DVS events generated by dynamic scene motion or dust activity."""
    def __init__(self, sensor_width: int = 346, sensor_height: int = 260):
        self.width = sensor_width
        self.height = sensor_height

    def generate_event_burst(
        self,
        motion_speed_mps: float,
        num_events: int = 500,
        seed: int = 42
    ) -> List[Dict]:
        """Generates realistic asynchronous event packets (x, y, timestamp_us, polarity)."""
        rng = np.random.RandomState(seed)
        events = []
        base_time_us = 1000000 # 1.0 s
        
        # Event rate scales with vehicle motion and vibration
        time_spread_us = int(max(1000, 20000.0 / (motion_speed_mps + 0.1)))
        
        for i in range(num_candidates := num_events):
            x = int(rng.randint(0, self.width))
            y = int(rng.randint(0, self.height))
            t = int(base_time_us + rng.randint(0, time_spread_us))
            p = 1 if rng.uniform(0, 1) > 0.5 else -1
            events.append({'x': x, 'y': y, 't_us': t, 'p': p})
            
        # Events sorted by microsecond timestamp
        events.sort(key=lambda e: e['t_us'])
        return events


class SpikingHazardFilter:
    """Leaky Integrate-and-Fire (LIF) spiking neural network for low-power hazard detection."""
    def __init__(self, membrane_decay: float = 0.95, v_thresh: float = 0.35):
        self.membrane_decay = membrane_decay
        self.v_thresh = v_thresh
        self.membrane_potential = 0.0
        self.spike_count = 0
        self.radiation_bitflip_detected = False

    def process_events(self, events: List[Dict]) -> Dict:
        """Accumulates event activity into membrane potential and fires spikes."""
        self.membrane_potential = 0.0
        self.spike_count = 0
        
        for ev in events:
            # Integrate event weight
            self.membrane_potential = self.membrane_potential * self.membrane_decay + 0.08 * ev['p']
            if self.membrane_potential >= self.v_thresh:
                self.spike_count += 1
                self.membrane_potential = 0.0 # reset
            elif self.membrane_potential <= -self.v_thresh:
                self.membrane_potential = 0.0
                
        # Hazard condition triggered by high spike density (e.g. dust devil or fast slippage)
        spike_rate_hz = self.spike_count * 10.0
